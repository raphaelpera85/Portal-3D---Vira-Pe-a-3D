type SeededPrinterFields = Partial<Pick<PrinterEntry,
  "buildVolumeDescription" | "buildVolumeMm" | "extruders" | "filamentDiameterMm" | "maxNozzleTemperatureC"
  | "maxBedTemperatureC" | "heatedBed" | "enclosure" | "maximumSpeedMmPerSecond" | "maximumSpeedDescription"
  | "maximumPowerWatts" | "measuredAveragePowerWatts" | "multicolorSlots" | "multicolorSystem" | "technicalProperties"
>>;
function seededPrinter(
  record: Pick<PrinterEntry, "id" | "brand" | "model" | "variant" | "technology"> & SeededPrinterFields
    & { sourceUrl: string; documentationUrl?: string; sourceLabel?: string; checkedAt?: string },
): PrinterEntry {
  const { sourceUrl, documentationUrl = sourceUrl, sourceLabel = `${record.brand} — ${record.model}`, checkedAt = "2026-11-12", ...fields } = record;
  const variantName = fields.variant === "standard" ? "" : ` ${fields.variant}`;
  return {
    name: `${fields.brand} ${fields.model}${variantName}`,
    buildVolumeDescription: null, buildVolumeMm: null, extruders: null, filamentDiameterMm: null,
    maxNozzleTemperatureC: null, maxBedTemperatureC: null, heatedBed: null, enclosure: null,
    maximumSpeedMmPerSecond: null, maximumPowerWatts: null, measuredAveragePowerWatts: null,
    multicolorSlots: null, multicolorSystem: null, supportedMaterials: {},
    ...fields,
    sources: [
      { label: sourceLabel, url: sourceUrl, checkedAt },
      ...(documentationUrl !== sourceUrl ? [{ label: `${record.brand} — documentação oficial`, url: documentationUrl, checkedAt }] : []),
    ],
  };
}
